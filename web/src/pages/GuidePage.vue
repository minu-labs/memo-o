    <div class="wrap narrow prose">
      <h1>사용법</h1>
      <p class="muted">설치부터 녹음, 텍스트 변환, 내보내기까지 MemoO 사용 방법을 정리했습니다.</p>

      <ul class="toc">
        <li v-for="t in toc" :key="t.id"><a :href="`#${t.id}`">{{ t.label }}</a></li>
      </ul>

      <h2 id="install">1. 설치하기</h2>
      <ol class="steps">
        <li><b>다운로드 버튼</b>을 눌러 설치 파일({{ INSTALLER_SIZE }})을 받습니다.</li>
        <li>
          실행하면 "Windows의 PC 보호" 경고가 뜰 수 있습니다. 개인이 배포하는 프로그램이라 코드
          서명 인증서가 없어서 나오는 안내이며, <b>추가 정보 → 실행</b>을 누르면 설치가 진행됩니다.
        </li>
        <li>설치 마법사에서 바탕화면 아이콘 생성 여부를 선택할 수 있습니다(기본 선택됨). 시작 메뉴에도 자동으로 등록됩니다.</li>
        <li>설치가 끝나면 바탕화면 또는 시작 메뉴의 MemoO 아이콘으로 바로 실행할 수 있습니다.</li>
      </ol>
      <p class="muted small">
        관리자 권한이 없어도 사용자 폴더에 설치할 수 있습니다. 설치 위치를 물어보는 화면에서 선택하세요.
      </p>

      <h2 id="first-run">2. 처음 실행할 때</h2>
      <p>
        처음 실행하면 녹음 관련 법적 고지와 개인정보 안내 화면이 뜹니다. 내용을 확인했다는 체크박스를
        선택해야 <b>시작하기</b> 버튼이 활성화됩니다. 한 번 확인하면 다음부터는 뜨지 않습니다.
      </p>

      <h2 id="record">3. 녹음하기</h2>
      <ol class="steps">
        <li>메인 화면 상단의 <b>마이크 선택</b> 드롭다운에서 사용할 마이크를 고릅니다. "기본 마이크"를 두면 Windows의 기본 입력 장치를 그대로 씁니다.</li>
        <li>가운데 빨간 원형 버튼(또는 <b>Space</b> 키)을 누르면 녹음이 시작됩니다. 버튼 아이콘이 흰 사각형으로 바뀌고 경과 시간이 올라갑니다.</li>
        <li>다시 누르면 녹음이 멈추고, 제목을 입력하는 창이 뜹니다. 비워두면 날짜/시간이 기본 제목으로 저장됩니다.</li>
        <li>녹음을 멈추는 즉시 텍스트 변환 대기열에 들어가고, 자동으로 시작됩니다.</li>
      </ol>
      <div class="notice">
        <h2>녹음은 적법하게 사용해주세요</h2>
        <p>
          본인이 참여한 대화의 녹음은 상대방의 동의 없이도 가능하지만, 본인이 참여하지 않은
          대화를 몰래 녹음하는 것은 불법이며 형사처벌 대상입니다. 사용 책임은 사용자에게 있습니다.
        </p>
      </div>

      <h2 id="while-recording">4. 녹음 중 다른 화면 보기</h2>
      <p>
        녹음 중에도 목록·상세 화면을 자유롭게 오갈 수 있습니다. 화면 위쪽에 남은 녹음 시간이
        빨간 배지로 표시되며, 눌러서 언제든 녹음 화면으로 돌아올 수 있습니다. 창을 최소화하면
        작은 캡슐 모양의 알림창이 화면 구석에 떠서, 녹음을 지켜보거나 바로 정지할 수 있습니다.
      </p>

      <h2 id="browse">5. 목록에서 찾아보기</h2>
      <p>
        <b>녹음 목록 전체보기</b>를 누르면 카드형 목록이 나옵니다. 제목이나 변환된 내용으로 검색할
        수 있고, 각 항목 오른쪽에 상태(완료 · 변환 중 · 변환 대기 · 오류)가 표시됩니다.
      </p>

      <h2 id="detail">6. 재생하고 검색하기</h2>
      <ol class="steps">
        <li>목록에서 항목을 클릭하면 상세 화면이 열립니다. 재생/일시정지, 10초 앞/뒤 이동, 구간 슬라이더를 쓸 수 있습니다.</li>
        <li>변환된 텍스트에서 문장을 클릭하면 그 시점부터 바로 재생됩니다.</li>
        <li>상단 검색창에 단어를 입력하면 일치하는 문장이 강조 표시됩니다.</li>
        <li>변환이 아직 진행 중이어도 녹음은 바로 재생할 수 있습니다. 변환이 끝나면 화면이 자동으로 갱신됩니다.</li>
        <li>변환에 실패한 경우 화면에 "다시 변환하기" 링크가 나타납니다.</li>
      </ol>

      <h2 id="export">7. 내보내기</h2>
      <p>상세 화면 아래의 <b>내보내기</b> 버튼에서 네 가지 형식으로 저장할 수 있습니다.</p>
      <ul>
        <li><b>텍스트 파일(.txt)</b> — 타임스탬프가 붙은 전체 텍스트</li>
        <li><b>자막 파일(.srt)</b> — 영상 편집 프로그램에서 자막으로 불러올 수 있는 형식</li>
        <li><b>텍스트 복사</b> — 클립보드로 바로 복사</li>
        <li><b>음성 파일(.wav)</b> — 녹음 원본</li>
      </ul>

      <h2 id="settings">8. 설정</h2>
      <p>
        오른쪽 위 메뉴(⋯) → <b>설정</b>에서 두 가지를 바꿀 수 있습니다.
      </p>
      <ul>
        <li><b>변환 모델</b> — 기본은 small(빠름)입니다. 더 정확한 medium 모델은 용량이 커서 기본 설치에 포함되지 않으며, 다운로드 페이지에서 별도로 받아 안내된 폴더에 넣으면 설정에서 선택할 수 있습니다.</li>
        <li><b>테마</b> — 라이트/다크 중 선택할 수 있습니다.</li>
      </ul>
      <p class="muted small">NVIDIA GPU(CUDA)가 있으면 설치 없이 자동으로 감지해 변환 속도를 높입니다.</p>

      <h2 id="shortcuts">9. 단축키</h2>
      <ul>
        <li><code>Space</code> — 녹음 화면에서는 녹음 시작/정지, 상세 화면에서는 재생/일시정지</li>
        <li><code>Esc</code> — 상세 화면에서 목록으로 돌아가기</li>
      </ul>

      <h2 id="data">10. 데이터는 어디에 저장되나요</h2>
      <p>
        녹음 파일과 변환된 텍스트는 모두 이 PC의 <code>%LOCALAPPDATA%\MemoO</code> 폴더에만 저장되며
        외부로 전송되지 않습니다. 메뉴(⋯) → <b>데이터 폴더 열기</b>로 바로 열어볼 수 있습니다.
        프로그램을 제거할 때 이 폴더를 함께 지울지 선택할 수 있습니다.
      </p>

      <h2 id="troubleshooting">11. 잘 안 될 때</h2>
      <details class="faq">
        <summary>녹음은 됐는데 재생해보니 소리가 없어요</summary>
        <p>
          대부분 재생이 아니라 <b>녹음 시점에 소리가 들어오지 않은 경우</b>입니다. 순서대로 확인해보세요.
        </p>
        <ol class="steps">
          <li>Windows 설정 → 개인 정보 및 보안 → 마이크에서 "데스크톱 앱이 마이크에 액세스하도록 허용"이 켜져 있는지 확인합니다.</li>
          <li>노트북의 마이크 음소거 단축키(Fn 키 조합)나 물리 스위치가 켜져 있지 않은지 확인합니다.</li>
          <li>제어판 → 소리 → 녹음 탭에서 사용 중인 마이크를 선택한 뒤 말해보고, 입력 막대가 움직이는지 확인합니다. 여기서도 안 움직이면 MemoO가 아니라 Windows/하드웨어 쪽 설정 문제입니다.</li>
          <li>같은 속성 창의 고급 탭에서 "독점 모드로 사용"이 켜져 있고 Zoom·Teams 등 다른 프로그램이 마이크를 쓰고 있으면 충돌할 수 있습니다. 다른 프로그램을 끄고 다시 시도해보세요.</li>
        </ol>
      </details>
      <details class="faq">
        <summary>텍스트 변환이 "오류"로 표시돼요</summary>
        <p>
          상세 화면에 오류 메시지가 함께 표시됩니다. 모델 파일이 없다는 내용이면 설정에서 모델이
          제대로 선택되어 있는지 확인하세요. 오류 화면의 "다시 변환하기"를 누르면 재시도합니다.
        </p>
      </details>
      <details class="faq">
        <summary>변환 속도가 너무 느려요</summary>
        <p>
          일반 사무용 PC(CPU)에서는 보통 녹음 길이보다 짧은 시간에 변환이 끝납니다. 계속 느리다면
          설정에서 medium 대신 small 모델을 선택해보세요. NVIDIA GPU가 있다면 자동으로 가속되므로
          그래픽 드라이버가 최신인지 확인하는 것도 도움이 됩니다.
        </p>
      </details>
      <details class="faq">
        <summary>실행 파일을 지웠는데 녹음 파일도 같이 지워지나요</summary>
        <p>
          제거 과정에서 데이터 폴더(<code>%LOCALAPPDATA%\MemoO</code>)를 함께 지울지 물어봅니다.
          "아니요"를 선택하면 나중에 다시 설치했을 때 그대로 이어서 쓸 수 있습니다.
        </p>
      </details>

